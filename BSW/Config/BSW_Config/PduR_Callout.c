uint8 PduR_GetDirection(void)
{
    uint8 Did437c_Byte18 = *(volatile uint8*)(0x0101A1AFU);
    uint8 RetVal = 0;
    switch (Did437c_Byte18)
    {
    case 0:
        /* not set*/
        RetVal = 0;
        break;
    
    case 1:
        /* Left */
        RetVal = 1;
        break;

    case 2:
        /* Right */
        RetVal = 2;
        break;
        
    default:
        RetVal = 3;
        break;
    }
    return RetVal;
}